export function formatFloat(imaskString) {
    if (!imaskString) { return 0.0; }

    // Remove everything except digits, commas and dots
    let cleaned = imaskString.replace(/[^\d.,]/g, '');

    // Remove thousands separator (dot) then convert decimal comma to dot
    cleaned = cleaned.replace(/\./g, '').replace(',', '.');

    const result = parseFloat(cleaned);

    return isNaN(result) ? 0.0 : result;
}

export function formatInt(imaskString){
    if(!imaskString){ return 0.0; }

    return parseInt(imaskString);
}

/**
 * 1. Calculate Sell Price
 */
function calculateSellPrice(cost, tax, fee, margin) {
    const divisor = 1 - tax - fee - margin;
    if (divisor <= 0) {
        throw new Error("Invalid inputs: Combined deductions (tax + fee + margin) must be less than 100%.");
    }
    return roundTo(cost / divisor, 2); // Currency usually 2 decimals
}

